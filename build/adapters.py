OPENCODE_BRIDGE = '''/**
 * Neva hook bridge for OpenCode. The whole policy lives in Python: this file only
 * forwards OpenCode's plugin events to plugins/neva-core/hooks/dispatch.py in the
 * Claude payload shape and turns its answer into something OpenCode enforces.
 * Zero dependencies.
 *
 * Decisions. dispatch.py exits 2 with a reason on stderr when a module blocks, and a
 * confirmation it cannot show on this harness also arrives as a block. OpenCode has no
 * return-value veto for tool.execute.before, so a block is re-raised as a throw, which
 * is the documented way a plugin stops a tool call. A permissionDecision of ask or
 * deny on stdout is thrown the same way: OpenCode has no prompt to show it in, and a
 * confirmation nobody sees must never become permission.
 *
 * Failure. A configured bridge never lets a tool call through on a dispatcher it could
 * not hear from. python3 missing, a timeout, a signal, an exit other than 0 or 2, or
 * stdout that is not a JSON object all block the tool call with the cause and a retry
 * instruction. Session and post-tool events stay best effort: there is nothing to guard.
 *
 * Context. additionalContext and systemMessage are delivered through
 * experimental.chat.system.transform. SessionStart context stays for the whole session;
 * context from a tool call is delivered once, on the next model turn.
 *
 * Runtime root. Copied skills, commands and agents run scripts under
 * ${CLAUDE_PLUGIN_ROOT}, which only Claude Code sets. shell.env supplies it, pointing at
 * plugins/neva-core in the checkout, so every script and its dependencies resolve.
 *
 * Set NEVA_ROOT to the Neva checkout. Without it the bridge stays silent rather
 * than guessing a path and failing on every single event.
 */
import { spawnSync } from "node:child_process";
import { join } from "node:path";

const NEVA_ROOT = process.env.NEVA_ROOT || "";
const DISPATCH = NEVA_ROOT
  ? join(NEVA_ROOT, "plugins", "neva-core", "hooks", "dispatch.py")
  : "";
const CONFIRM =
  "This action needs confirmation in an interactive session, and OpenCode cannot show " +
  "Neva's confirmation prompt, so it was blocked. Fix: run it from Claude Code, or have " +
  "the owner confirm and run it themselves.";

const TIMEOUT_MS = Number(process.env.NEVA_BRIDGE_TIMEOUT_MS) || 20000;

const sessionContext = new Map();
const pendingContext = new Map();

function failed(failure) {
  return { code: -1, stderr: "", out: {}, failure };
}

function dispatch(event, payload) {
  if (!DISPATCH) return { code: 0, stderr: "", out: {}, failure: "" };
  const run = spawnSync("python3", [DISPATCH, event], {
    input: JSON.stringify({ ...payload, hook_event_name: event }),
    env: { ...process.env, NEVA_HARNESS: "opencode" },
    encoding: "utf8",
    timeout: TIMEOUT_MS,
    killSignal: "SIGKILL",
  });
  if (run.error) {
    if (run.error.code === "ETIMEDOUT") return failed("timed out after " + TIMEOUT_MS + " ms");
    return failed("could not start python3 (" + (run.error.code || run.error.message) + ")");
  }
  if (run.signal) return failed("was killed by " + run.signal);
  if (run.status !== 0 && run.status !== 2) {
    const tail = (run.stderr || "").trim().split("\\n").slice(-1)[0] || "no stderr";
    return failed("exited with status " + run.status + " (" + tail + ")");
  }
  let out = {};
  const text = (run.stdout || "").trim();
  if (text) {
    try {
      out = JSON.parse(text);
    } catch {
      return failed("printed output that is not a JSON object");
    }
    if (!out || typeof out !== "object" || Array.isArray(out)) {
      return failed("printed output that is not a JSON object");
    }
  }
  return { code: run.status, stderr: run.stderr || "", out, failure: "" };
}

function refuse(tool, failure) {
  return new Error(
    "Neva's guard dispatcher " + failure + ", so this " + tool + " call was blocked rather " +
    "than run unchecked. Fix: check that python3 runs and that NEVA_ROOT (" + NEVA_ROOT +
    ") is the Neva checkout, read hooks.log in the Neva data directory, then retry the call.");
}

function contextOf(out) {
  const hso = out.hookSpecificOutput || {};
  return [hso.additionalContext, out.systemMessage].filter(Boolean).join("\\n\\n");
}

function queue(sessionID, text) {
  if (!text) return;
  const id = sessionID || "";
  pendingContext.set(id, [...(pendingContext.get(id) || []), text]);
}

export const NevaHooks = async ({ directory, worktree }) => {
  const cwd = worktree || directory || process.cwd();
  return {
    "tool.execute.before": async (input, output) => {
      const result = dispatch("PreToolUse", {
        tool: { name: input.tool, input: output.args },
        session_id: input.sessionID,
        cwd,
      });
      if (result.failure) throw refuse(input.tool, result.failure);
      if (result.code === 2) throw new Error(result.stderr.trim() || "blocked by Neva");
      const hso = result.out.hookSpecificOutput || {};
      if (hso.permissionDecision === "deny") {
        throw new Error(hso.permissionDecisionReason || "blocked by Neva");
      }
      if (hso.permissionDecision === "ask") {
        throw new Error([hso.permissionDecisionReason, CONFIRM].filter(Boolean).join("\\n\\n"));
      }
      queue(input.sessionID, contextOf(result.out));
    },
    "tool.execute.after": async (input, output) => {
      const result = dispatch("PostToolUse", {
        tool: { name: input.tool, input: input.args || {} },
        tool_response: output?.output ?? "",
        session_id: input.sessionID,
        cwd,
      });
      queue(input.sessionID, contextOf(result.out));
    },
    "shell.env": async (input, output) => {
      if (!NEVA_ROOT) return;
      output.env.NEVA_ROOT = output.env.NEVA_ROOT || NEVA_ROOT;
      output.env.CLAUDE_PLUGIN_ROOT =
        output.env.CLAUDE_PLUGIN_ROOT || join(NEVA_ROOT, "plugins", "neva-core");
    },
    "experimental.chat.system.transform": async (input, output) => {
      const id = input.sessionID || "";
      const base = sessionContext.get(id);
      if (base) output.system.push(base);
      const pending = pendingContext.get(id);
      if (pending && pending.length) output.system.push(pending.join("\\n\\n"));
      pendingContext.delete(id);
    },
    event: async ({ event }) => {
      if (event.type === "session.created") {
        const id = event.properties?.info?.id || "";
        const result = dispatch("SessionStart", { session: { id }, cwd });
        const text = contextOf(result.out);
        if (text) sessionContext.set(id, text);
      } else if (event.type === "session.idle") {
        dispatch("Stop", { session: { id: event.properties?.sessionID || "" }, cwd });
      }
    },
  };
};
'''


@harness("opencode")
def build_opencode(root, version, licence):
    """OpenCode's global layer: ~/.config/opencode holds agents, commands, skills, plugins,
    AGENTS.md and opencode.json, all documented global paths. The neva installer writes only
    inside HOME, so the adapter installs there rather than into one project's .opencode/."""
    base = Path("opencode")
    copy_tree(root, CORE / "skills", base / "skills")
    for stem, description, model, body in agent_pages():
        write_markdown(root, base / "agents" / (stem + ".md"),
                       ["description: " + quote(description), "mode: subagent"], body)
    for stem, description, body in command_pages():
        write_markdown(root, base / "commands" / (stem + ".md"),
                       ["description: " + quote(description)], body)
    for stem, title, text in rule_pages():
        write_text(root, base / "rules" / (stem + ".md"), marked(text, ".md"))
    write_text(root, base / "AGENTS.md", marked(instructions("Neva for OpenCode"), ".md"))
    write_text(root, base / "plugins" / "neva-hooks.js", marked(OPENCODE_BRIDGE, ".js"))
    write_json(root, base / "opencode.json", {
        "$schema": "https://opencode.ai/config.json",
        # OpenCode expands a leading ~/ in instructions, so this works from every project.
        "instructions": ["~/.config/opencode/rules/neva-core/*.md"],
    })
    write_install(root, "opencode", [
        # A neva/ subfolder each, never the owner's own names: OpenCode scans agents/**,
        # commands/** and skills/** recursively, naming agents and commands neva/<name>.
        entry("agents", "~/.config/opencode/agents/neva"),
        entry("commands", "~/.config/opencode/commands/neva"),
        entry("skills", "~/.config/opencode/skills/neva"),
        entry("rules", "~/.config/opencode/rules/neva-core"),
        entry("plugins/neva-hooks.js", "~/.config/opencode/plugins/neva-hooks.js"),
        entry("AGENTS.md", "~/.config/opencode/AGENTS.md", "append-block", BLOCK_KEY),
        # The owner's own instruction globs live in the same array: add ours, keep theirs.
        entry("opencode.json", "~/.config/opencode/opencode.json", "append-json", "instructions"),
    ], binaries=["opencode"], paths=["~/.config/opencode", ".opencode", "opencode.json"], post=[
        "export NEVA_ROOT=<path to the Neva checkout>   # the hook bridge stays off without it",
    ])


# ---------------------------------------------------------------- cursor

@harness("cursor")
def build_cursor(root, version, licence):
    """Cursor reads .mdc rules with description/alwaysApply, and plain markdown agents."""
    base = Path("cursor")
    for stem, title, text in rule_pages():
        always = "true" if stem == "process" else "false"
        write_markdown(root, base / ".cursor" / "rules" / ("neva-" + stem + ".mdc"),
                       ["description: " + quote("Neva " + title), "alwaysApply: " + always], text)
    for stem, description, model, body in agent_pages():
        write_markdown(root, base / ".cursor" / "agents" / ("neva-" + stem + ".md"),
                       ["name: " + quote("neva-" + stem), "description: " + quote(description)], body)
    write_install(root, "cursor", [
        entry(".cursor/rules", ".cursor/rules"),
        entry(".cursor/agents", ".cursor/agents"),
    ], binaries=["cursor"], paths=[".cursor"], post=[
        "export NEVA_ROOT=<path to the Neva checkout>",
        RUNTIME_ROOT_NOTE,
    ])


# ---------------------------------------------------------------- gemini

def toml_string(text):
    """A TOML basic string. TOML's escapes are the JSON ones, so json.dumps is exact."""
    return json.dumps(text, ensure_ascii=False)


@harness("gemini")
def build_gemini(root, version, licence):
    """A real Gemini CLI extension: manifest, context file, TOML commands, skills, agents."""
    base = Path("gemini")
    write_text(root, base / "GEMINI.md", marked(instructions("Neva for Gemini CLI"), ".md"))
    for stem, description, body in command_pages():
        # Gemini commands are TOML with a required `prompt`. Its argument placeholder is
        # {{args}}, never $ARGUMENTS, so the body gets the Gemini spelling appended.
        write_text(root, base / "commands" / (stem + ".toml"),
                   "# " + MARK + "\n"
                   + "description = " + toml_string(description) + "\n"
                   + "prompt = " + toml_string(body.lstrip("\n") + "\n\n{{args}}\n") + "\n")
    for stem, description, model, body in agent_pages():
        write_markdown(root, base / "agents" / (stem + ".md"),
                       ["name: " + quote(stem), "description: " + quote(description)], body)
    copy_tree(root, CORE / "skills", base / "skills")
    write_json(root, base / "gemini-extension.json", {
        "name": "neva",
        "version": version,
        "description": "Neva: a disciplined coding process, its skills, agents and commands.",
        "contextFileName": "GEMINI.md",
    })
    write_install(root, "gemini", [
        entry(".", "~/.gemini/extensions/neva"),
    ], binaries=["gemini"], paths=["~/.gemini", ".gemini"], post=[
        "export NEVA_ROOT=<path to the Neva checkout>",
        RUNTIME_ROOT_NOTE,
        "gemini extensions list   # confirm 'neva' is loaded",
    ])


