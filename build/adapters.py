#!/usr/bin/env python3
"""Generate the committed cross-harness adapter surfaces under adapters/.

plugins/neva-core is the single source of truth. This program only projects its
portable assets into the discovery layout each harness actually reads, so that a
change to the plugin is the only edit anyone makes. Run with --check in CI: it
exits non-zero when a generated file drifted from what the plugin would produce.

Every generated file carries a "do not edit" marker wherever the format has a
comment syntax. Markdown with YAML frontmatter gets the marker placed after the
closing delimiter, never before it: a marker on line 1 would push the frontmatter
off the top of the file and every harness would stop parsing it.
"""
import argparse
import json
import shutil
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / "plugins" / "neva-core"
OUT = ROOT / "adapters"
MARK = "generated by build/adapters.py from plugins/neva-core, do not edit"

TEXT_SUFFIXES = (".md", ".mdc", ".toml", ".yaml", ".yml", ".txt", ".py", ".sh", ".js", ".mjs", ".cjs")
MODES = ("copy", "symlink", "merge-json", "merge-toml", "append-block", "append-json")
BLOCK_KEY = "neva-core"

# Harness builders register themselves here so the adapter list has one source.
BUILDERS = {}


def harness(name):
    """Register a builder under its harness name. The name is also its directory."""
    def wrap(fn):
        BUILDERS[name] = fn
        return fn
    return wrap


# ---------------------------------------------------------------- source assets

def plugin_meta():
    """Version and licence come from the plugin manifest, never from a literal here."""
    data = json.loads((CORE / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))
    return str(data["version"]), str(data["license"])


def contained(path, root, what):
    """Refuse a path whose real location is outside root. Never trust the final leak scan
    to recognise a private file that a link or a ../ pulled into a generated adapter."""
    real_root = Path(root).resolve()
    real = Path(path).resolve()
    if real != real_root and real_root not in real.parents:
        raise SystemExit("adapters: " + what + " " + str(path) + " resolves outside " + str(root)
                         + ". Keep every source inside plugins/neva-core and every output inside adapters/.")
    return path


def check_source(path):
    if Path(path).is_symlink():
        raise SystemExit("adapters: " + str(path) + " is a symlink. Generated adapters copy only real "
                         "files inside plugins/neva-core. Replace the link with the file itself.")
    return contained(path, CORE, "source")


def read(path):
    return check_source(path).read_text(encoding="utf-8")


def split_frontmatter(text):
    """Return (frontmatter_without_delimiters, body). Frontmatter is '' when absent."""
    if not text.startswith("---\n"):
        return "", text
    end = text.find("\n---\n", 3)
    if end < 0:
        return "", text
    return text[4:end + 1], text[end + 5:]


def field(frontmatter, key, default=""):
    """Read one top-level single-line scalar out of a frontmatter block.

    Deliberately not a YAML parser. Every source file in plugins/neva-core keeps its
    scalars on one line, and assert_single_line_fields() fails the build the moment
    that stops being true, so a silent truncation cannot reach a generated file.
    """
    for line in frontmatter.split("\n"):
        if line.startswith(key + ":"):
            value = line[len(key) + 1:].strip()
            if value[:1] == value[-1:] and value[:1] in ("'", '"'):
                value = value[1:-1]
            return value
    return default


def quote(value):
    """YAML double-quoted scalar. json.dumps is exact for the subset YAML shares."""
    return json.dumps(str(value), ensure_ascii=False)


def assert_single_line_fields(path, frontmatter):
    """Refuse to generate from a source whose frontmatter the field() reader cannot trust."""
    for line in frontmatter.split("\n"):
        for key in ("description", "name"):
            if line.startswith(key + ":") and line[len(key) + 1:].strip() in ("", "|", ">", "|-", ">-"):
                raise SystemExit(
                    "adapters: " + str(path) + " has a multi-line '" + key + ":'. "
                    "Generated adapters need single-line scalars. Put it on one line.")


def sources(kind, pattern="*.md"):
    return sorted((CORE / kind).glob(pattern))


# ---------------------------------------------------------------- marking and writing

def marked(text, suffix):
    """Insert the do-not-edit marker using the comment syntax the format supports."""
    suffix = suffix.lower()
    if suffix in (".md", ".mdc"):
        frontmatter, body = split_frontmatter(text)
        if frontmatter:
            return "---\n" + frontmatter + "---\n<!-- " + MARK + " -->\n" + body
        return "<!-- " + MARK + " -->\n" + text
    if suffix in (".toml", ".yaml", ".yml", ".txt", ".sh", ".py"):
        if text.startswith("#!"):
            first, _, rest = text.partition("\n")
            return first + "\n# " + MARK + "\n" + rest
        return "# " + MARK + "\n" + text
    if suffix in (".js", ".mjs", ".cjs"):
        # node accepts a shebang only on line 1, so the marker goes after it.
        if text.startswith("#!"):
            first, _, rest = text.partition("\n")
            return first + "\n// " + MARK + "\n" + rest
        return "// " + MARK + "\n" + text
    return text


def write_text(root, rel, text):
    path = contained(Path(root) / rel, root, "output")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def write_json(root, rel, value):
    """JSON has no comment syntax, so the marker becomes a leading key instead."""
    if isinstance(value, dict) and "_generated" not in value:
        value = dict(value, _generated=MARK)
    write_text(root, rel, json.dumps(value, indent=2, sort_keys=True) + "\n")


def write_markdown(root, rel, frontmatter_lines, body):
    """Write a harness-native markdown file with a frontmatter block we control."""
    head = "---\n" + "".join(line + "\n" for line in frontmatter_lines) + "---\n"
    write_text(root, rel, head + "<!-- " + MARK + " -->\n" + body.lstrip("\n"))


def is_executable(path):
    return bool(path.stat().st_mode & 0o111)


def copy_tree(root, source, destination):
    """Mirror a source directory, marking every text file it contains."""
    check_source(source)
    for path in sorted(source.rglob("*")):
        if "__pycache__" in path.parts:
            continue
        check_source(path)
        if not path.is_file():
            continue
        rel = destination / path.relative_to(source)
        if path.suffix.lower() in TEXT_SUFFIXES:
            text = read(path)
            assert_single_line_fields(path, split_frontmatter(text)[0])
            write_text(root, rel, marked(text, path.suffix))
        else:
            target = contained(root / rel, root, "output")
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
        # A skill tells the agent to run its scripts directly, so a copy that lost the
        # executable bit fails with permission denied. Git tracks only that one bit.
        if is_executable(path):
            (root / rel).chmod(0o755)


# ---------------------------------------------------------------- install contract

# Skills, commands and agents run scripts under ${CLAUDE_PLUGIN_ROOT}, which only Claude
# Code sets. Harnesses without a bridge that supplies it get this printed instead.
RUNTIME_ROOT_NOTE = ('export CLAUDE_PLUGIN_ROOT="$NEVA_ROOT/plugins/neva-core"   '
                     "# skills, commands and agents run scripts under it")

def entry(src, dest, mode="copy", key=""):
    if mode not in MODES:
        raise SystemExit("adapters: unknown install mode " + repr(mode))
    if mode in ("merge-json", "merge-toml", "append-block", "append-json") and not key:
        raise SystemExit("adapters: mode " + mode + " needs a key for " + dest)
    return {"src": src, "dest": dest, "mode": mode, "key": key}


def write_install(root, name, entries, binaries=(), paths=(), post=()):
    write_json(root, Path(name) / "install.json", {
        "harness": name,
        "detect": {"binaries": list(binaries), "paths": list(paths)},
        "entries": entries,
        "post": list(post),
    })


def instructions(title, extra=""):
    """The portable instruction body every harness gets: Neva's canonical process."""
    text = read(CORE / "rules" / "process.md")
    head = "# " + title + "\n\nThis is Neva's working process, generated from the Neva plugin.\n"
    return head + (extra + "\n" if extra else "") + "\n" + text


def first_heading(text, default="Neva rule"):
    for line in text.split("\n"):
        if line.startswith("# "):
            return line[2:].strip()
    return default


def rule_pages():
    """Every portable rule, as (stem, title, text). README is the index, not a rule."""
    pages = []
    for path in sources("rules"):
        if path.name == "README.md":
            continue
        text = read(path)
        pages.append((path.stem, first_heading(text, path.stem), text))
    return pages


def agent_pages():
    pages = []
    for path in sources("agents"):
        frontmatter, body = split_frontmatter(read(path))
        assert_single_line_fields(path, frontmatter)
        pages.append((path.stem, field(frontmatter, "description"), field(frontmatter, "model"), body))
    return pages


def command_pages():
    pages = []
    for path in sources("commands"):
        frontmatter, body = split_frontmatter(read(path))
        assert_single_line_fields(path, frontmatter)
        pages.append((path.stem, field(frontmatter, "description"), body))
    return pages


