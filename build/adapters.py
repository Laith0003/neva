# ---------------------------------------------------------------- driver

def build_into(root):
    version, licence = plugin_meta()
    for name in sorted(BUILDERS):
        BUILDERS[name](root, version, licence)
    build_readme(root, version)


def tree_bytes(root):
    """Every generated file's bytes and executable bit: drift in either is drift."""
    return {p.relative_to(root).as_posix(): (p.read_bytes(), is_executable(p))
            for p in sorted(root.rglob("*")) if p.is_file()}


def expected_tree():
    with tempfile.TemporaryDirectory(prefix="neva-adapters-") as tmp:
        root = Path(tmp)
        build_into(root)
        return tree_bytes(root)


def check(verbose=True):
    """Exit status 1 on any drift between adapters/ and what the plugin would produce."""
    expected = expected_tree()
    actual = tree_bytes(OUT) if OUT.exists() else {}
    if expected == actual:
        if verbose:
            print("adapters: clean")
        return 0
    missing = sorted(set(expected) - set(actual))
    extra = sorted(set(actual) - set(expected))
    changed = sorted(p for p in set(expected) & set(actual) if expected[p] != actual[p])
    if verbose:
        for kind, paths in (("missing", missing), ("extra", extra), ("changed", changed)):
            for path in paths:
                print("adapters: " + kind + " " + path, file=sys.stderr)
        print("adapters: drift in " + str(len(missing) + len(extra) + len(changed))
              + " file(s); run: python3 build/adapters.py", file=sys.stderr)
    return 1


def generate(verbose=True):
    """Build into a temporary tree first, so a crash never leaves adapters/ half written."""
    with tempfile.TemporaryDirectory(prefix="neva-adapters-") as tmp:
        staged = Path(tmp) / "adapters"
        build_into(staged)
        if OUT.exists():
            shutil.rmtree(OUT)
        shutil.copytree(staged, OUT)
    if verbose:
        print("adapters: generated " + str(len(tree_bytes(OUT))) + " file(s) for "
              + str(len(BUILDERS)) + " harnesses")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 when a generated file drifted; change nothing")
    parser.add_argument("--quiet", action="store_true", help="suppress progress output")
    args = parser.parse_args(argv)
    return check(not args.quiet) if args.check else generate(not args.quiet)


if __name__ == "__main__":
    raise SystemExit(main())
