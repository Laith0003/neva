README_HEAD = """<!-- GENMARK -->
# Harness adapters

`plugins/neva-core` is the single source of truth. Everything under `adapters/` is
generated from it by `build/adapters.py` and committed, so a reader can see exactly what
each harness receives without running anything.

Change the plugin, then run:

```
python3 build/adapters.py          # regenerate, then commit adapters/
python3 build/adapters.py --check  # exits 1 on drift; CI runs this
```

Never edit a file under `adapters/` by hand. The next generate overwrites it, and
`--check` fails in the meantime. Every generated file says so in its own comment syntax;
JSON has none, so it carries a `_generated` key instead.

## Harnesses

| Harness | Surface | Hooks |
|---|---|---|
| `codex` | Registers Neva as a Codex marketplace, plus AGENTS.md | yes, via dispatch.py |
| `opencode` | Native agents, commands, skills, rules, AGENTS.md | yes, via a JS bridge to dispatch.py |
| `cursor` | `.cursor/rules/*.mdc` and `.cursor/agents/*.md` | no |
| `gemini` | A Gemini CLI extension: manifest, GEMINI.md, TOML commands, skills, agents | no |
| `zed` `kiro` `qwen` `kimi` `trae` `windsurf` `antigravity` `github-copilot` `codebuddy` `pi` `hermes` | Instructions, and a rules directory where the harness has one | no |

Each harness directory is written to paths that harness's own documentation states. Where
a path could not be verified it is marked in that harness's `install.json` `post` notes
rather than shipped as though it were certain.

### Codex uses the Claude marketplace

Codex reads Claude-format plugin marketplaces: a stock `~/.codex/config.toml` registers
`anthropics/claude-plugins-official` next to OpenAI's own. Neva already ships
`.claude-plugin/marketplace.json`, so the Codex adapter registers this repository instead
of copying its skills and agents into a second tree that would drift. `adapters/codex/`
therefore holds only what Codex cannot get from the marketplace: the AGENTS.md
instructions, a `hooks.json` wired to the same `dispatch.py`, and the config fragment.

## The install.json contract

Every harness directory contains an `install.json`, and `bin/neva` reads it:
`neva install --harness <name> --yes` applies its entries, `neva repair` re-applies any
Neva-owned entry that went missing or was changed, and `neva uninstall` takes back exactly
what install wrote and nothing else. Each write is recorded in Neva's install-state manifest with a checksum
and, where a file existed, a backup, so uninstall can hand the owner's files back byte for
byte. The installer never guesses from the directory layout. Each harness is rehearsed as a
dry run against the real files before the first write, so a contract with a mode it does not
know, or any entry it would refuse, leaves nothing written.

```json
{
  "harness": "<name>",
  "detect": { "binaries": ["<executable>"], "paths": ["<file or dir that implies this harness>"] },
  "entries": [
    { "src": "<path relative to adapters/<harness>>",
      "dest": "<destination: ~/... or ${VAR}/..., inside HOME>",
      "mode": "copy | symlink | merge-json | merge-toml | append-block | append-json",
      "key": "<required for every mode except copy and symlink, empty otherwise>" }
  ],
  "post": ["<a line the installer prints for the person to run or read>"]
}
```

| Field | Meaning |
|---|---|
| `harness` | The name, always equal to the directory name. |
| `detect.binaries` | Executables that, on `PATH`, suggest the harness is installed. Reported by `neva list`, never proof. |
| `detect.paths` | Config files or directories that suggest the same. `~` and `${VAR}` are allowed. |
| `entries[].src` | Relative to the harness directory. A file, or a directory whose files are installed one by one, each its own manifest entry. A symlink in the source is refused. |
| `entries[].dest` | Where it goes. `~` and `${VAR}` expand; an unset variable is refused by name (export `CODEX_HOME` for Codex). The result must be absolute and inside HOME. A relative dest is a project file the installer refuses: copy those into the project by hand. |
| `entries[].mode` | How to apply it, below. |
| `entries[].key` | The dotted JSON key, TOML table, or block name. A part may be quoted as TOML quotes it, `plugins."neva-core@neva"`. Required for `merge-json`, `merge-toml`, `append-block` and `append-json`; empty otherwise. |
| `post` | Lines the installer prints after the entries. It never runs them. Some are commands, some are caveats about the harness. |

### Modes

| Mode | Behaviour |
|---|---|
| `copy` | Copy the file to `dest`, or every file of a directory under `dest`. A single file that was there is backed up first and restored on uninstall; for a directory, a file already at a destination that Neva does not own is refused by name and nothing is written. |
| `symlink` | Link `dest` at `src` so plugin edits appear without reinstalling. |
| `merge-json` | Set `key` in the JSON object at `dest` to the value at `key` in `src`, leaving every other key alone. Uninstall puts back the value that was there, or removes the key. |
| `merge-toml` | The same for one TOML table or value. A new table is appended at the end so every other byte and comment stays; uninstall takes exactly those bytes off. One entry per table. |
| `append-json` | The value at `key` in `src` is an array, or an object whose values are arrays. Its entries are added beside the owner's in the matching arrays at `dest`, and every source entry must contain `neva-core`. Neva owns exactly the entries the manifest records it wrote, compared whole and only in the arrays the source covers: a reinstall replaces those, uninstall removes those and any container Neva created, and an entry the owner already had is never added twice. Any other entry that mentions `neva-core` is the owner's, named on install and left alone, and a Neva entry the owner has edited is refused by name rather than discarded. Used for Codex hooks and OpenCode instructions. |
| `append-block` | Add `src` to `dest` between the lines `# neva begin neva-core` and `# neva end neva-core` (the key names the block), replacing an existing block of that name. Uninstall removes the block and restores the file to its prior bytes. |

`post` is printed, never executed. An adapter cannot make the installer run a command
silently, which is the point: the contract carries data, not instructions to obey.

The installer expands `~` and `${VAR}` in `dest` only, never inside merged values. Codex's
`config.toml` tables carry `${CODEX_HOME}` and `${NEVA_ROOT}` literally, so its `post` lines
say to replace them by hand.
"""


