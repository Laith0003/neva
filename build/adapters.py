def rule_frontmatter(flavour, stem, title, always):
    """The frontmatter each harness requires on a rule file, in its own vocabulary."""
    description = quote("Neva " + title)
    if flavour == "kiro":
        # inclusion: always | fileMatch | manual | auto. Frontmatter must be the first byte.
        # "auto" pulls a rule in when the request matches its description; "manual" would
        # hide every rule but process behind a #mention nobody would think to type.
        return ["inclusion: " + ("always" if always else "auto"),
                "name: " + quote("neva-" + stem), "description: " + description]
    if flavour == "windsurf":
        # trigger: always_on | glob | model_decision | manual.
        return ["trigger: " + ("always_on" if always else "model_decision"),
                "description: " + description]
    if flavour == "antigravity":
        # An unrecognised trigger makes Antigravity discard the rule without a word.
        return ["trigger: " + ("always_on" if always else "model_decision"),
                "description: " + description]
    if flavour == "copilot":
        return ["applyTo: " + quote("**"), "description: " + description]
    if flavour == "codebuddy":
        return ["alwaysApply: " + ("true" if always else "false"), "description: " + description]
    if flavour == "qwen":
        return ["description: " + description]
    raise SystemExit("adapters: no rule frontmatter defined for " + repr(flavour))


def pack_filename(flavour, stem):
    if flavour == "copilot":
        return "neva-" + stem + ".instructions.md"
    return "neva-" + stem + ".md"


def build_pack(root, name, spec):
    base = Path(name)
    entries = []
    if spec["instruction"]:
        src, dest = spec["instruction"]
        write_text(root, base / src, marked(instructions("Neva for " + name), ".md"))
        # The destination is a file the person also writes in (AGENTS.md, QWEN.md, a global
        # instruction file). A copy would replace their rules; the marked block joins them.
        entries.append(entry(src, dest, "append-block", BLOCK_KEY))
    if spec["rules"]:
        directory, dest, flavour = spec["rules"]
        for stem, title, text in rule_pages():
            write_markdown(root, base / directory / pack_filename(flavour, stem),
                           rule_frontmatter(flavour, stem, title, stem == "process"), text)
        entries.append(entry(directory, dest))
    write_install(root, name, entries, binaries=spec["binaries"], paths=spec["paths"],
                  post=[spec["note"]] if spec["note"] else [])


# Bind each pack name as a default argument. A closure over the loop variable would make
# every builder write the last harness in the table.
for _name, _spec in PACKS.items():
    def _pack_builder(root, version, licence, name=_name, spec=_spec):
        build_pack(root, name, spec)
    BUILDERS[_name] = _pack_builder


