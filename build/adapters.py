CODEX_EVENTS = (
    ("SessionStart", "*"),
    ("UserPromptSubmit", "*"),
    ("PreToolUse", "*"),
    ("PostToolUse", "*"),
    ("Stop", "*"),
)


@harness("codex")
def build_codex(root, version, licence):
    base = Path("codex")
    write_text(root, base / "AGENTS.md", marked(instructions("Neva for Codex"), ".md"))

    # Codex's hook payload is snake_case and field-for-field identical to Claude's, so no
    # translation is needed. NEVA_HARNESS is still set, so an observation records which
    # harness it came from rather than being filed under Claude.
    hooks = {}
    for event, matcher in CODEX_EVENTS:
        hooks[event] = [{"matcher": matcher, "hooks": [{
            "type": "command",
            "command": 'NEVA_HARNESS=codex python3 "${NEVA_ROOT}/plugins/neva-core/hooks/dispatch.py" ' + event,
            "timeout": 20,
        }]}]
    write_json(root, base / "hooks.json", {"hooks": hooks})

    # Codex registers an agent role only through [agents.<role>].config_file. There is no
    # auto-discovered agents directory, so every role is both written and registered here.
    roles = []
    for stem, description, model, body in agent_pages():
        role = stem.replace("-", "_")
        write_text(root, base / "agents" / (stem + ".toml"),
                   "# " + MARK + "\n"
                   + "name = " + toml_string(role) + "\n"
                   + "description = " + toml_string(description) + "\n"
                   + "developer_instructions = " + toml_string(body.lstrip("\n")) + "\n")
        roles.append((role, stem, description))

    config = ["# " + MARK,
              "# Merge into ${CODEX_HOME}/config.toml (default ~/.codex/config.toml).",
              "# Codex reads Claude-format marketplaces, so the source is this repository:",
              "# its .claude-plugin/marketplace.json is the manifest Codex consumes.",
              "",
              "[marketplaces.neva]",
              'source_type = "local"',
              'source = "${NEVA_ROOT}"',
              "",
              '[plugins."neva-core@neva"]',
              "enabled = true",
              ""]
    for role, stem, description in roles:
        config += ["[agents." + role + "]",
                   "description = " + toml_string(description),
                   'config_file = "${CODEX_HOME}/neva/agents/' + stem + '.toml"',
                   ""]
    write_text(root, base / "config.toml", "\n".join(config))

    # merge-toml sets exactly one table, so every table config.toml carries gets its own
    # entry. Merging only marketplaces.neva left the plugin disabled and every role file
    # installed but unregistered, which Codex treats as if it did not exist.
    tables = ["marketplaces.neva", 'plugins."neva-core@neva"'] + ["agents." + role for role, _, _ in roles]
    write_install(root, "codex", [
        entry("AGENTS.md", "${CODEX_HOME}/AGENTS.md", "append-block", BLOCK_KEY),
        # The owner's own hooks share these event arrays: add Neva's groups, keep theirs.
        entry("hooks.json", "${CODEX_HOME}/hooks.json", "append-json", "hooks"),
        entry("agents", "${CODEX_HOME}/neva/agents"),
    ] + [entry("config.toml", "${CODEX_HOME}/config.toml", "merge-toml", table) for table in tables],
        binaries=["codex"], paths=["${CODEX_HOME}", "~/.codex", "~/.codex/config.toml"], post=[
        "export NEVA_ROOT=<path to the Neva checkout>   # hooks.json refers to it",
        RUNTIME_ROOT_NOTE,
        "codex plugin marketplace add <path to the Neva checkout>",
        "codex plugin add neva-core@neva",
        "codex plugin list   # confirm neva-core is installed",
        "Codex will not run a hook until it is trusted. Review the hooks in Codex and "
        "accept them: an untrusted hooks.json is silently inert.",
        "Codex does not expand ${CODEX_HOME} or ${NEVA_ROOT} in config.toml. Replace them "
        "with real paths when you merge the tables by hand.",
    ])


